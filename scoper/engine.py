"""Assemble a 4-week Statement of Work from a ScopeProfile.

Content is template-driven and deterministic: the same inputs always
produce the same SOW. Optional LLM polishing, if configured, only
rewrites the problem summary and never changes structure or facts.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from typing import Any

from scoper.detect import ScopeProfile
from scoper import packs


@dataclass
class WeekPlan:
    week: int
    title: str
    goals: list[str]
    activities: list[str]
    deliverables: list[str]


@dataclass
class ThreatRow:
    stride: str
    threat: str
    mitigation: str
    priority: str


@dataclass
class KpiRow:
    metric: str
    baseline: str
    target: str
    how_measured: str


@dataclass
class RiskRow:
    risk: str
    likelihood: str
    impact: str
    mitigation: str


@dataclass
class StaffRow:
    role: str
    time: str
    responsibilities: str


@dataclass
class StatementOfWork:
    title: str
    customer_name: str
    generated_on: str
    disclaimer: str
    problem_summary: str
    assumptions: list[str]
    in_scope: list[str]
    out_of_scope: list[str]
    weeks: list[WeekPlan]
    architecture_narrative: str
    architecture_mermaid: str
    threats: list[ThreatRow]
    kpis: list[KpiRow]
    risks: list[RiskRow]
    staffing: list[StaffRow]
    compliance: list[str]
    profile: ScopeProfile
    llm_used: bool = False
    llm_note: str = ""
    extras: dict[str, Any] = field(default_factory=dict)


DISCLAIMER = (
    "This document was generated by the Automated Architecture Scoper, "
    "a portfolio demo. It is a starting point for a human-led discovery "
    "conversation — not a production architecture, a security assessment, "
    "or a legally binding statement of work. Every section should be "
    "reviewed with the customer before it is used in a real engagement."
)


def _comma(items: list[str]) -> str:
    items = [i for i in items if i]
    if not items:
        return "the named teams"
    if len(items) == 1:
        return items[0]
    if len(items) == 2:
        return f"{items[0]} and {items[1]}"
    return ", ".join(items[:-1]) + f", and {items[-1]}"


def _node_id(label: str, used: dict[str, str]) -> str:
    base = "".join(ch for ch in label.title() if ch.isalnum()) or "Node"
    base = base[:24]
    candidate = base
    n = 2
    existing = set(used.values())
    while candidate in existing:
        candidate = f"{base}{n}"
        n += 1
    used[label] = candidate
    return candidate


def _esc(label: str) -> str:
    return label.replace('"', "'")


def build_mermaid(profile: ScopeProfile) -> str:
    ids: dict[str, str] = {}
    user_labels = profile.departments[:4] or ["Business users"]
    system_labels = profile.existing_systems[:5]
    use_case = profile.use_cases[0] if profile.use_cases else "AI assistant"

    lines = ["flowchart TB"]
    lines.append('  subgraph Users["Users"]')
    for label in user_labels:
        lines.append(f'    {_node_id("u-"+label, ids)}["{_esc(label)}"]')
    lines.append("  end")
    lines.append('  subgraph Existing["Existing systems"]')
    for label in system_labels:
        lines.append(f'    {_node_id("s-"+label, ids)}["{_esc(label)}"]')
    lines.append("  end")
    lines.append('  subgraph Slice["Proposed 4-week thin slice"]')
    lines.append('    CONN["Read-only data connector"]')
    lines.append('    GOV["Access control and audit log"]')
    lines.append(f'    APP["{_esc(use_case)}"]')
    lines.append("  end")
    for label in system_labels:
        lines.append(f"  {ids['s-'+label]} --> CONN")
    lines.append("  CONN --> GOV --> APP")
    for label in user_labels:
        lines.append(f"  {ids['u-'+label]} --> APP")
    return "\n".join(lines)


def generate_sow(
    profile: ScopeProfile,
    generated_on: date | None = None,
    polish_summary: bool = True,
) -> StatementOfWork:
    """Build a complete SOW. Optional LLM polish is applied only if configured."""
    day = (generated_on or date.today()).isoformat()
    pack = packs.for_industry(profile.industry_id)
    departments = _comma(profile.departments)
    systems = _comma(profile.existing_systems)
    use_cases = _comma(profile.use_cases)
    data_types = _comma(profile.data_types)
    sites = (
        f"{profile.site_count} sites"
        if profile.site_count
        else "the customer footprint (site count to be confirmed)"
    )

    problem_summary = pack["problem_summary"].format(
        customer=profile.customer_name,
        industry=profile.industry_label,
        departments=departments,
        use_cases=use_cases,
        systems=systems,
        data_types=data_types,
        size_hint=profile.size_hint,
        sites=sites,
        sensitivity=profile.sensitivity,
        team_size=profile.team_size,
        ask=profile.raw_ask,
    )

    assumptions = [item.format(systems=systems, sites=sites, departments=departments) for item in pack["assumptions"]]
    in_scope = [item.format(use_cases=use_cases, systems=systems, departments=departments) for item in pack["in_scope"]]
    out_of_scope = list(pack["out_of_scope"])

    weeks = [
        WeekPlan(
            week=item["week"],
            title=item["title"],
            goals=[g.format(departments=departments, systems=systems, use_cases=use_cases, sites=sites) for g in item["goals"]],
            activities=[a.format(departments=departments, systems=systems, use_cases=use_cases, sites=sites) for a in item["activities"]],
            deliverables=[d.format(departments=departments, systems=systems, use_cases=use_cases, sites=sites) for d in item["deliverables"]],
        )
        for item in pack["weeks"]
    ]

    mermaid = build_mermaid(profile)
    narrative = pack["architecture_narrative"].format(
        systems=systems,
        use_cases=use_cases,
        departments=departments,
        sensitivity=profile.sensitivity,
        compliance=_comma(profile.compliance),
    )

    threats = [ThreatRow(**row) for row in pack["threats"]]
    kpis = [KpiRow(**row) for row in pack["kpis"]]
    risks = [RiskRow(**row) for row in pack["risks"]]
    staffing = [StaffRow(**row) for row in pack["staffing"]]

    sow = StatementOfWork(
        title=f"4-Week Statement of Work: AI Scoping Engagement — {profile.customer_name}",
        customer_name=profile.customer_name,
        generated_on=day,
        disclaimer=DISCLAIMER,
        problem_summary=problem_summary,
        assumptions=assumptions,
        in_scope=in_scope,
        out_of_scope=out_of_scope,
        weeks=weeks,
        architecture_narrative=narrative,
        architecture_mermaid=mermaid,
        threats=threats,
        kpis=kpis,
        risks=risks,
        staffing=staffing,
        compliance=profile.compliance,
        profile=profile,
    )

    if polish_summary:
        from scoper.llm import maybe_polish_summary

        sow.problem_summary, sow.llm_used, sow.llm_note = maybe_polish_summary(
            sow.problem_summary, profile
        )

    return sow
