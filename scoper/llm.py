"""Optional LLM polish for the problem-summary paragraph.

Default behavior: do nothing. The app must run fully offline with no
API key. If the user sets OPENAI_API_KEY (and optionally OPENAI_BASE_URL
/ OPENAI_MODEL for a local Ollama or other OpenAI-compatible endpoint),
we ask the model only to tighten the already-generated summary. Structure,
KPIs, and threat-model rows are never generated by the model.

Any failure (timeout, bad key, network) falls back to the rules-engine
text and is reported in the SOW.
"""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.request
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from scoper.detect import ScopeProfile

SYSTEM_PROMPT = (
    "You tighten a problem-summary paragraph for a 4-week AI scoping "
    "Statement of Work. Keep the same facts, industry, systems, and data "
    "sensitivity. Do not invent systems, metrics, or commitments. Do not "
    "add a title or bullet list. Return only the revised summary, in 2 or "
    "3 short paragraphs, plain language, no markdown headings."
)


def llm_config() -> dict[str, str] | None:
    key = os.environ.get("OPENAI_API_KEY", "").strip()
    if not key:
        return None
    base = os.environ.get("OPENAI_BASE_URL") or os.environ.get("OPENAI_API_BASE") or "https://api.openai.com/v1"
    base = base.rstrip("/")
    model = os.environ.get("OPENAI_MODEL", "gpt-4o-mini")
    return {"key": key, "base": base, "model": model}


def maybe_polish_summary(summary: str, profile: "ScopeProfile") -> tuple[str, bool, str]:
    """Return (text, used_llm, note). Never raises to the caller."""
    cfg = llm_config()
    if not cfg:
        return summary, False, "No OPENAI_API_KEY set; used the rules-engine text."

    payload = {
        "model": cfg["model"],
        "temperature": 0.2,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {
                "role": "user",
                "content": (
                    f"Industry: {profile.industry_label}\n"
                    f"Systems: {', '.join(profile.existing_systems)}\n"
                    f"Data types: {', '.join(profile.data_types)}\n\n"
                    f"Summary to tighten:\n{summary}"
                ),
            },
        ],
    }
    url = cfg["base"] + "/chat/completions"
    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {cfg['key']}",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            body = json.loads(resp.read().decode("utf-8"))
        text = body["choices"][0]["message"]["content"].strip()
        if not text:
            return summary, False, "LLM returned an empty summary; kept the rules-engine text."
        note = f"Problem summary polished with {cfg['model']} at {cfg['base']}. Other sections remain rules-based."
        return text, True, note
    except Exception as exc:  # noqa: BLE001 — fallback is the product behavior
        return summary, False, f"LLM polish failed ({type(exc).__name__}: {exc}); kept the rules-engine text."
